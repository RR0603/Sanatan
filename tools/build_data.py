#!/usr/bin/env python3
"""Builds the static sky data used by the app.

Inputs (download into a scratch directory and pass it as the first argument):
  hygdata_v41.csv            https://github.com/astronexus/HYG-Database  (CC BY-SA 4.0)
  constellations.lines.json  https://github.com/ofrohn/d3-celestial       (BSD-3-Clause)
  constellations.json        https://github.com/ofrohn/d3-celestial
  mw.json                    https://github.com/ofrohn/d3-celestial

Outputs:
  js/data/stars.js           stars to magnitude 6.0 (J2000), sorted by brightness
  js/data/constellations.js  IAU stick figures + names (en / hi)
  img/milkyway.png           Milky Way brightness map in galactic coordinates

Usage: python3 tools/build_data.py <download-dir>
"""
import csv
import json
import math
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAG_LIMIT = 6.0

# J2000 equatorial -> galactic rotation
EQ2GAL = np.array([
    [-0.0548755604, -0.8734370902, -0.4838350155],
    [0.4941094279, -0.4448296300, 0.7469822445],
    [-0.8676661490, -0.1980763734, 0.4559837762],
])


def build_stars(src):
    rows = []
    with open(os.path.join(src, "hygdata_v41.csv")) as f:
        for r in csv.DictReader(f):
            if r["id"] == "0":
                continue  # the Sun
            try:
                mag = float(r["mag"])
            except ValueError:
                continue
            if mag > MAG_LIMIT:
                continue
            ci = float(r["ci"]) if r["ci"] else 0.6
            rows.append((mag, float(r["ra"]) * 15.0, float(r["dec"]), ci,
                         r["bayer"], r["flam"], r["con"], r["proper"], r["hip"]))
    rows.sort(key=lambda x: x[0])

    flat, keys, names = [], {}, {}
    for i, (mag, ra, dec, ci, bayer, flam, con, proper, hip) in enumerate(rows):
        flat += [round(ra, 4), round(dec, 4), round(mag, 2), round(ci, 2)]
        cand = []
        if bayer and con:
            cand.append(f"{bayer} {con}")
            if "-" in bayer:  # "Gam-2 Ari" also answers to "Gam Ari" (brightest wins)
                cand.append(f"{bayer.split('-')[0]} {con}")
        if flam and con:
            cand.append(f"{flam} {con}")
        if hip:
            cand.append(f"HIP {hip}")
        for k in cand:
            keys.setdefault(k, i)
        if proper:
            names[i] = proper

    out = os.path.join(ROOT, "js", "data", "stars.js")
    with open(out, "w") as f:
        f.write("// Generated by tools/build_data.py from the HYG database v4.1 (CC BY-SA 4.0).\n")
        f.write("// d: [raDeg, decDeg, mag, B-V] * n, J2000, sorted bright to faint.\n")
        f.write("window.LS_DATA = window.LS_DATA || {};\n")
        f.write("LS_DATA.stars = ")
        json.dump({"n": len(rows), "d": flat, "keys": keys, "names": names}, f,
                  separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"stars: {len(rows)} -> {out} ({os.path.getsize(out) // 1024} KB)")


def build_constellations(src):
    lines = json.load(open(os.path.join(src, "constellations.lines.json")))
    meta = json.load(open(os.path.join(src, "constellations.json")))
    info = {}
    for feat in meta["features"]:
        p = feat["properties"]
        info[feat["id"]] = {
            "la": p["name"], "en": p.get("en") or p["name"], "hi": p.get("hi") or p["name"],
            "pos": [round(c, 3) for c in feat["geometry"]["coordinates"]], "rank": int(p["rank"]),
        }
    figs = []
    for feat in lines["features"]:
        cid = feat["id"]
        polylines = [[[round(c[0], 3), round(c[1], 3)] for c in seg]
                     for seg in feat["geometry"]["coordinates"]]
        entry = {"id": cid, "l": polylines}
        entry.update(info.get(cid, {}))
        figs.append(entry)
    out = os.path.join(ROOT, "js", "data", "constellations.js")
    with open(out, "w") as f:
        f.write("// Generated by tools/build_data.py from d3-celestial (BSD-3-Clause), J2000 degrees.\n")
        f.write("window.LS_DATA = window.LS_DATA || {};\n")
        f.write("LS_DATA.constellations = ")
        json.dump(figs, f, separators=(",", ":"), ensure_ascii=False)
        f.write(";\n")
    print(f"constellations: {len(figs)} -> {out} ({os.path.getsize(out) // 1024} KB)")


def to_galactic(ra_deg, dec_deg):
    ra, dec = np.radians(ra_deg), np.radians(dec_deg)
    v = np.stack([np.cos(dec) * np.cos(ra), np.cos(dec) * np.sin(ra), np.sin(dec)])
    g = EQ2GAL @ v
    l = np.degrees(np.arctan2(g[1], g[0])) % 360.0
    b = np.degrees(np.arcsin(np.clip(g[2], -1, 1)))
    return l, b


def build_milkyway(src, width=2048, height=1024):
    mw = json.load(open(os.path.join(src, "mw.json")))
    l_cols = (np.arange(width) + 0.5) / width * 360.0
    b_rows = 90.0 - (np.arange(height) + 0.5) / height * 180.0
    acc = np.zeros((height, width), dtype=np.float32)
    weights = [1.0, 0.9, 0.8, 0.7, 0.6]

    for level, feat in enumerate(mw["features"]):
        segs = []
        for poly in feat["geometry"]["coordinates"]:
            for ring in poly:
                arr = np.array(ring, dtype=np.float64)
                l, b = to_galactic(arr[:, 0], arr[:, 1])
                l2, b2 = np.roll(l, -1), np.roll(b, -1)
                segs.append(np.stack([l, b, l2, b2], axis=1))
        s = np.concatenate(segs)
        l1, b1, l2, b2 = s.T
        dl = (l2 - l1 + 180.0) % 360.0 - 180.0
        keep = np.abs(dl) > 1e-9
        l1, b1, b2, dl = l1[keep], b1[keep], b2[keep], dl[keep]

        inside = np.zeros((height, width), dtype=np.uint8)
        # Even-odd test with a ray from each pixel toward the galactic north pole.
        for x, lc in enumerate(l_cols):
            off = np.where(dl > 0, (lc - l1) % 360.0, (l1 - lc) % 360.0)
            t = off / np.abs(dl)
            hit = t < 1.0
            bc = np.sort(b1[hit] + t[hit] * (b2[hit] - b1[hit]))
            above = len(bc) - np.searchsorted(bc, b_rows, side="right")
            inside[:, x] = above & 1
        acc += inside * weights[level]
        print(f"  milky way level {level + 1}: {inside.mean() * 100:.1f}% of sky")

    def blur(arr, radius):
        im = Image.fromarray(np.clip(arr * 255, 0, 255).astype(np.uint8), "L")
        return np.asarray(im.filter(ImageFilter.GaussianBlur(radius=radius))).astype(np.float32) / 255.0

    acc /= acc.max()
    # Sharp structure + soft halo + a faint diffuse glow hugging the galactic plane.
    halo = blur(acc, 18.0)
    diffuse = np.exp(-(b_rows[:, None] / 14.0) ** 2) * (0.55 + 0.45 * np.cos(np.radians(l_cols))[None, :] ** 2)
    a = 0.75 * blur(acc, 3.5) + 0.6 * halo + 0.12 * diffuse
    a = np.power(a / a.max(), 0.85)
    img = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8), "L")
    out = os.path.join(ROOT, "img", "milkyway.png")
    img.save(out, optimize=True)
    print(f"milky way -> {out} ({os.path.getsize(out) // 1024} KB)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build_stars(sys.argv[1])
    build_constellations(sys.argv[1])
    build_milkyway(sys.argv[1])
